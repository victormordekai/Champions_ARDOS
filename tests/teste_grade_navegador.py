import json, sys
from pathlib import Path
from playwright.sync_api import sync_playwright
RAIZ = Path(__file__).resolve().parent.parent
CAP = RAIZ / 'tests' / 'capturas'; CAP.mkdir(exist_ok=True)
ok, falhas = [], []
def c(cond, r): (ok if cond else falhas).append(r)
with sync_playwright() as p:
    b = p.chromium.launch(executable_path="/usr/bin/google-chrome")
    for larg, nome in ((1280, 'larga'), (390, 'estreita')):
        pg = b.new_page(viewport={'width': larg, 'height': 900}, accept_downloads=True)
        erros = []
        pg.on('pageerror', lambda e: erros.append(str(e)))
        pg.on('console', lambda m: erros.append(m.text) if m.type == 'error' else None)
        pg.on('dialog', lambda d: d.accept())
        pg.goto((RAIZ / 'cliente_ardos.html').as_uri())
        pg.click('a[href="grade_pedido.html"]')
        pg.wait_for_timeout(300)
        c('grade_pedido.html' in pg.url, f'{nome}: link do cliente abre a grade')
        c(pg.locator('#gp-envio-online').count() == 0, f'{nome}: sem endpoint, envio online não aparece')
        pg.click('#gp-revisar')
        c('código do pedido' in pg.inner_text('#gp-erros'), f'{nome}: recusa sem código')
        pg.fill('#gp-codigo', 'teste-0001')
        c(pg.input_value('#gp-codigo') == 'TESTE-0001', f'{nome}: código em maiúsculas')
        eq1 = pg.locator('.gp-equipe').nth(0)
        eq1.locator('input[id^=nome-]').fill('time alfa')
        eq1.locator('select[id^=tam-]').nth(0).select_option('ADULTO|M')
        eq1.locator('input[aria-label^="Nome na peça"]').nth(0).fill('<img src=x onerror=alert(1)>')
        eq1.locator('input[aria-label^="Número"]').nth(0).fill('007')
        c(eq1.locator('input[aria-label^="Número"]').nth(0).input_value() == '007', f'{nome}: número com zero preservado')
        eq1.get_by_role('button', name='＋ Adicionar pessoa').click()
        eq1 = pg.locator('.gp-equipe').nth(0)
        eq1.locator('select[id^=tam-]').nth(1).select_option('INF|10')
        eq1.locator('select[aria-label^="Posição"]').nth(1).select_option('TORCIDA')
        # segunda equipe: torcida com produtos diferentes e tamanhos por peça
        pg.click('#gp-add-equipe')
        eq2 = pg.locator('.gp-equipe').nth(1)
        eq2.locator('input[id^=nome-]').fill('torcida alfa')
        eq2.locator('label.gp-chip', has_text='Camisa manga curta').click()
        eq2 = pg.locator('.gp-equipe').nth(1)
        eq2.locator('label.gp-chip', has_text='Calção').click()
        eq2 = pg.locator('.gp-equipe').nth(1)
        eq2.locator('label.gp-chip', has_text='Camiseta').click()
        eq2 = pg.locator('.gp-equipe').nth(1)
        eq2.locator('label.gp-chip', has_text='Corta-vento').click()
        eq2 = pg.locator('.gp-equipe').nth(1)
        eq2.locator('.gp-mesmo input').click()
        eq2 = pg.locator('.gp-equipe').nth(1)
        c(eq2.locator('select[id^=tam-]').count() == 2, f'{nome}: tamanho por peça quando desmarca "mesmo tamanho"')
        eq2.locator('select[id^=tam-]').nth(0).select_option('ADULTO|G')
        eq2.locator('select[aria-label^="Posição"]').nth(0).select_option('TORCIDA')
        c(pg.locator('.gp-equipe').nth(0).locator('img').count() == 0, f'{nome}: nome não vira HTML')
        pg.click('#gp-revisar')
        c(pg.is_visible('#gp-revisao'), f'{nome}: revisão aberta')
        res = pg.inner_text('#gp-resumo')
        c('TORCIDA 1' in res and 'Camiseta: 1' in res and 'Corta-vento' not in res.split('TORCIDA ALFA')[1].split('Camiseta')[0], f'{nome}: resumo com torcida e peças por equipe')
        c('10 INF × 1' in res, f'{nome}: tamanho infantil no resumo')
        with pg.expect_download() as d:
            pg.click('#gp-salvar')
        arq = d.value.path()
        env = json.loads(Path(arq).read_text())
        c(env['schema'] == 'champions.ardos.grade-web.v1' and env['equipes'][0]['atletas'][0]['numero'] == '007', f'{nome}: arquivo no contrato do Core')
        c(env['equipes'][0]['atletas'][1]['posicao'] == 'TORCIDA', f'{nome}: TORCIDA no arquivo')
        pg.goto((RAIZ / 'grade_pedido.html').as_uri())
        pg.set_input_files('#gp-arquivo', arq)
        pg.wait_for_timeout(200)
        c('2 equipe' in pg.inner_text('#gp-status-arquivo'), f'{nome}: continua de um arquivo')
        c(pg.input_value('#gp-codigo') == 'TESTE-0001', f'{nome}: código volta do arquivo')
        pg.click('#gp-revisar')
        pg.screenshot(path=str(CAP / f'grade_{nome}.png'), full_page=True)
        w = pg.evaluate('document.documentElement.scrollWidth')
        c(w <= larg + 1, f'{nome}: sem rolagem horizontal ({w}px)')
        c(not erros, f'{nome}: sem erro de console {erros[:2]}')
        pg.close()
    b.close()
for o in ok: print('OK   ', o)
for f in falhas: print('FALHA', f)
print(len(ok), 'aprovadas,', len(falhas), 'falhas'); sys.exit(1 if falhas else 0)
